import { chromium } from '@playwright/test'
import { strict as assert } from 'node:assert'
import JSZip from 'jszip'

const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
assert.equal(await page.getByRole('heading', { name: 'A Few Good Uploads' }).count(), 1)
assert.equal(await page.locator('.opening-image img').evaluate(image => image.naturalWidth > 0), true)
await page.screenshot({ path: '/tmp/a-few-good-uploads-desktop.png', fullPage: true })
await page.keyboard.press('ArrowRight')
assert.equal(await page.getByRole('heading', { name: 'The Case Before the Court' }).count(), 1)
await page.getByRole('button', { name: 'Next slide' }).focus()
await page.keyboard.press('ArrowRight')
assert.equal(await page.getByRole('heading', { name: 'What Is a DOCX File?' }).count(), 1)
await page.getByRole('button', { name: 'Open slide overview' }).click()
await page.getByRole('button', { name: /Live Demonstration/ }).click()
await page.getByRole('button', { name: 'OPEN THE FORENSICS LAB' }).last().click()
await page.getByRole('button', { name: /Exhibit A Conventional Drafting/ }).click()
await page.getByRole('heading', { name: 'Exhibit-A-synthetic.docx' }).waitFor()
assert.equal(await page.getByText('Exhibit-A-synthetic.docx').count(), 1)
await page.getByRole('button', { name: 'Metadata', exact: true }).click()
assert.equal(await page.getByText('Casey Example').count() >= 1, true)
await page.getByRole('button', { name: 'Structure', exact: true }).click()
assert.equal(await page.getByText('insertion', { exact: true }).count(), 1)
await page.getByRole('button', { name: 'Raw evidence', exact: true }).click()
assert.equal(await page.locator('pre').textContent().then(text => text.includes('w:document')), true)
await page.getByRole('button', { name: 'BACK TO PRESENTATION' }).click()
assert.equal(await page.getByRole('heading', { name: 'Live Demonstration' }).count(), 1)
await page.getByRole('button', { name: 'OPEN FORENSICS LAB' }).first().click()
assert.equal(await page.getByText('Exhibit-A-synthetic.docx').count(), 1)
const downloadPromise = page.waitForEvent('download')
await page.getByRole('button', { name: 'Download synthetic exhibit A' }).click()
const file = await downloadPromise
const zip = await JSZip.loadAsync(await (await file.createReadStream()).toArray().then(chunks => Buffer.concat(chunks)))
const compressed = await zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' })
await page.locator('input[type=file]').setInputFiles({ name: 'compressed.docx', mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', buffer: compressed })
await page.getByText('compressed.docx', { exact: true }).waitFor()
assert.equal(await page.getByText('SYNTHETIC EXHIBIT · SUPPLIED KNOWN HISTORY').count(), 0)
await page.screenshot({ path: '/tmp/a-few-good-uploads-lab.png', fullPage: true })
await page.setViewportSize({ width: 390, height: 844 })
await page.getByRole('button', { name: 'BACK TO PRESENTATION' }).click()
await page.getByRole('button', { name: 'Go to opening slide' }).click()
await page.screenshot({ path: '/tmp/a-few-good-uploads-mobile.png', fullPage: true })
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'Mobile presentation should not overflow horizontally')
await page.getByRole('button', { name: 'OPEN FORENSICS LAB' }).first().click()
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'Mobile lab should not overflow horizontally')
assert.deepEqual(errors, [])
await browser.close()
console.log('Browser smoke test passed: navigation, exhibits, compressed upload, persistence, XML and mobile layout.')